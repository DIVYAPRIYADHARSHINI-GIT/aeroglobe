// Builds src/lib/data/airports.ts from OurAirports public-domain CSV (/tmp/airports.csv).
import { readFileSync, writeFileSync } from 'node:fs';

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else q = false; }
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const rows = parseCsv(readFileSync('/tmp/airports.csv', 'utf8'));
const head = rows[0];
const ix = Object.fromEntries(head.map((h, i) => [h, i]));
const all = rows.slice(1).filter((r) => r.length > 5);

// Major airports: large_airport with a real IATA code and scheduled service.
const large = all.filter((r) =>
  r[ix.type] === 'large_airport' && r[ix.iata_code]?.length === 3 && r[ix.scheduled_service] === 'yes'
);

// Always include the world's best-known hubs (used for demo routes + landing copy),
// then cap the remaining large airports per country so the ~300 markers stay globally spread
// instead of being dominated by the US.
const HUBS = new Set(['ATL','DFW','DEN','ORD','LAX','JFK','EWR','SFO','SEA','MIA','PHX','IAH','LAS','BOS','MCO','CLT','MSP','DTW','PHL','YYZ','YVR','MEX','GRU','GIG','EZE','BOG','LIM','SCL','LHR','LGW','CDG','ORY','AMS','FRA','MUC','MAD','BCN','FCO','MXP','IST','SAW','SVO','DME','LED','ZRH','VIE','CPH','ARN','OSL','HEL','DUB','BRU','LIS','ATH','WAW','PRG','BUD','MAN','EDI','DEL','BOM','BLR','MAA','HYD','CCU','COK','AMD','PNQ','GOI','DXB','AUH','DOH','RUH','JED','KWI','BAH','MCT','TLV','CAI','JNB','CPT','NBO','LOS','ADD','CMN','HKG','PVG','PEK','PKX','CAN','SZX','CTU','NRT','HND','KIX','ICN','GMP','TPE','SIN','KUL','BKK','DMK','CGK','DPS','MNL','HAN','SGN','SYD','MEL','BNE','PER','AKL','CHC','KTM','CMB','DAC','ISB','KHI','LHE','TAS','ALA','BGW','THR']);
const CAP = 2;
const count = new Map();
const list = [];
for (const r of large) if (HUBS.has(r[ix.iata_code])) list.push(r);
const picked = new Set(list.map((r) => r[ix.iata_code]));
for (const r of list) count.set(r[ix.iso_country], (count.get(r[ix.iso_country]) ?? 0) + 1);
for (const r of large) {
  if (picked.has(r[ix.iata_code])) continue;
  const c = r[ix.iso_country];
  const n = count.get(c) ?? 0;
  if (n >= CAP) continue;
  count.set(c, n + 1);
  list.push(r);
}

const out = list
  .map((r) => ({
    iata: r[ix.iata_code],
    icao: r[ix.icao_code] || r[ix.gps_code] || '',
    name: r[ix.name].replace(/ International Airport$/, ' Intl').replace(/ Airport$/, ''),
    city: r[ix.municipality] || '',
    country: r[ix.iso_country],
    lat: Math.round(Number(r[ix.latitude_deg]) * 1e4) / 1e4,
    lon: Math.round(Number(r[ix.longitude_deg]) * 1e4) / 1e4
  }))
  .filter((a) => Number.isFinite(a.lat) && Number.isFinite(a.lon))
  .sort((a, b) => a.iata.localeCompare(b.iata));

const ts = `// AUTO-GENERATED by scripts/build-airports.mjs — do not edit by hand.\n// Source: OurAirports (https://ourairports.com/data/) — public domain.\n// ${out.length} major airports bundled for offline airport markers, search and demo routes.\n\nexport interface Airport {\n\tiata: string;\n\ticao: string;\n\tname: string;\n\tcity: string;\n\tcountry: string;\n\tlat: number;\n\tlon: number;\n}\n\nexport const AIRPORTS: Airport[] = ${JSON.stringify(out)};\n\nexport const AIRPORT_BY_IATA = new Map(AIRPORTS.map((a) => [a.iata, a]));\nexport const AIRPORT_BY_ICAO = new Map(AIRPORTS.filter((a) => a.icao).map((a) => [a.icao, a]));\n`;
writeFileSync('src/lib/data/airports.ts', ts);
console.log('airports:', out.length, 'countries:', new Set(out.map((a) => a.country)).size);
